def get_text(lang: str, key: str, **kwargs) -> str:
    """Get translated text by language and key"""
    keys = key.split('.')
    text = TRANSLATIONS.get(lang, TRANSLATIONS['en'])

    for k in keys:
        if isinstance(text, dict):
            text = text.get(k, key)
        else:
            return key

    if kwargs:
        try:
            return text.format(**kwargs)
        except:
            return text

    return text